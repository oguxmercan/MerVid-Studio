// Auto-detect system language
function detectSystemLanguage() {
  try {
    const navLangs = navigator.languages || [navigator.language || navigator.userLanguage];
    for (const lang of navLangs) {
      if (!lang) continue;
      const code = lang.toLowerCase().split('-')[0];
      if (TRANSLATIONS[code]) {
        return code;
      }
    }
  } catch (e) {
    console.error("Language detection error:", e);
  }
  return 'en'; // Default fallback
}

function getTranslation(key, lang = currentLanguage) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || key;
}

function applyLanguage(lang) {
  if (lang === 'auto') {
    currentLanguage = detectSystemLanguage();
  } else if (TRANSLATIONS[lang]) {
    currentLanguage = lang;
  } else {
    currentLanguage = 'en';
  }

  // Update text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = getTranslation(key);
    if (val) el.textContent = val;
  });

  // Update placeholder attributes with data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    const val = getTranslation(key);
    if (val) el.setAttribute('placeholder', val);
  });

  // Update title attributes with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = getTranslation(key);
    if (val) el.setAttribute('title', val);
  });

  // Store in localStorage for fast reload
  try {
    localStorage.setItem('mervid_language', lang);
  } catch (e) {}
}
